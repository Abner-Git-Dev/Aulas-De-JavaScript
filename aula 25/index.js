/*
Operadores de comparação
> - Maior que 
>= - Maior que ou igual a
< - Menor que
<= - Menor que ou igual a
== - Igualdade (valor)
=== - Igualdade estrita (valor e tipo)
!= - Diferente (valor)
!== - Diferente estrito (valor e tipo)
*/ 
const num1 = 10;  //number  
const num2 = '10';  // String
// O operador '==' Diz que o num1 e o num2 são iguais porem eles não são iguais, o num1 é um number e o num2 é uma string;
// por isso nao é usado o operador '==';

const comp = num1 === num2 ;

console.log(comp);

